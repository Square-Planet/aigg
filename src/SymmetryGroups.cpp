static size_t CountOrbitLength(FPoint const &s, FRotationMatrixList const &SymmetryOps) {
   // do stupid variant -- just make all of them, and compare them in O(N^2).
   FPointArray
      Rg_s(3, SymmetryOps.size());
   for (size_t iSymOp = 0; iSymOp != SymmetryOps.size(); ++ iSymOp)
      Rg_s.col(iSymOp) = SymmetryOps[iSymOp] * s;
   size_t
      nUniquePoints = 0;
   for (size_t ig0 = 0; ig0 != SymmetryOps.size(); ++ ig0) {
      bool unique = true;
      for (size_t ig1 = 0; ig1 != ig0; ++ ig1) {
         if ((Rg_s.col(ig0) - Rg_s.col(ig1)).squaredNorm() < 1e-15) {
            unique = false;
            break;
         }
      }
      if (unique)
         nUniquePoints += 1;
   }
   return nUniquePoints;
}


FRotationMatrixList ConvertToMatrixList(FQuaternionList const &ql)
{
   FRotationMatrixList
      r;
   FQuaternionList::const_iterator
      it;
   for (it = ql.begin(); it != ql.end(); ++ it)
      r.push_back(it->matrix());
   return r;
}


