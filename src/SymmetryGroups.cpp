   //        9  M(xyz)[ 0,16, 4]  wt = 3  eq-set = [( 0,16, 4), ( 4, 0,16), (16, 4, 0)]
   //       10  M(xyz)[ 0,18, 2]  wt = 3  eq-set = [( 0,18, 2), ( 2, 0,18), (18, 2, 0)]
   //       11  M(xyz)[ 2, 2,16]  wt = 3  eq-set = [( 2, 2,16), ( 2,16, 2), (16, 2, 2)]
   //       12  M(xyz)[ 2, 4,14]  wt = 3  eq-set = [( 2, 4,14), ( 4,14, 2), (14, 2, 4)]
   //       13  M(xyz)[ 2, 6,12]  wt = 3  eq-set = [( 2, 6,12), ( 6,12, 2), (12, 2, 6)]
   //       14  M(xyz)[ 2, 8,10]  wt = 3  eq-set = [( 2, 8,10), ( 8,10, 2), (10, 2, 8)]
