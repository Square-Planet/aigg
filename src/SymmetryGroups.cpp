         ops.push_back(Matrix3x3(0, 0, 1, 1, 0, 0, 0, 1, 0));    // [ 7] gix=(0,1,0,1)
         ops.push_back(Matrix3x3(0, -1, 0, 0, 0, -1, 1, 0, 0));  // [ 8] gix=(0,1,0,2)
