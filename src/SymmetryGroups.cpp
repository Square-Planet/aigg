FOrbitType const &FPointGroup::GetOrbitType(FPoint const &p) const
{
   // iterate through orbit types in reverse order. Find the most specialized
   // orbit type which 'p' is compatible with.
   //
   // (Note comments in class regarding FOrbitType::iType: more specialized
   // *orbits must* be added after more general orbits.)
   for (size_t iOrbitType = m_OrbitTypes.size() - 1; iOrbitType < m_OrbitTypes.size(); -- iOrbitType) {
      FOrbitType const
         &OrbitType = *m_OrbitTypes[iOrbitType];
      if (OrbitType.IsOnOrbit(p, s_fEpsilon))
         return OrbitType;
   }
   throw std::runtime_error(fmt::format("FPointGroup::GetOrbitType() failed for input point p=({:.12f},{:.12f},{:.12f}). Is the 'general' type of orbit missing for the current symmetry group?", double(p[0]), double(p[1]), double(p[2])));
}


size_t FPointGroup::CountOrbitLength(FPoint const &p) const
{
   return GetOrbitType(p).Length;
}


FOrbitTypeRawPtrList FPointGroup::GetOrbitTypes(FPointArray const &SeedPoints) const
{
   assert(SeedPoints.rows() == 3);
   size_t
      nPoints = size_t(SeedPoints.cols());
   FOrbitTypeRawPtrList
      r;
   r.reserve(nPoints);
   for (size_t iPoint = 0; iPoint != nPoints; ++ iPoint)
      r.push_back(&GetOrbitType(SeedPoints.col(iPoint)));
   return r;
}


