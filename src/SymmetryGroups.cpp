         ops.push_back(Matrix3x3(0, 1, 0, 0, 0, 1, 1, 0, 0));     // [11] gix=(0,1,1,2)
         ops.push_back(Matrix3x3(-1, 0, 0, 0, -1, 0, 0, 0, -1));  // [12] gix=(1,0,0,0)
         ops.push_back(Matrix3x3(0, 0, 1, 1, 0, 0, 0, -1, 0));    // [13] gix=(1,0,0,1)
         ops.push_back(Matrix3x3(0, 1, 0, 0, 0, -1, 1, 0, 0));    // [14] gix=(1,0,0,2)
         ops.push_back(Matrix3x3(-1, 0, 0, 0, 1, 0, 0, 0, 1));    // [15] gix=(1,0,1,0)
         ops.push_back(Matrix3x3(0, 0, -1, 1, 0, 0, 0, 1, 0));    // [16] gix=(1,0,1,1)
         ops.push_back(Matrix3x3(0, -1, 0, 0, 0, 1, 1, 0, 0));    // [17] gix=(1,0,1,2)
         ops.push_back(Matrix3x3(1, 0, 0, 0, -1, 0, 0, 0, 1));    // [18] gix=(1,1,0,0)
         ops.push_back(Matrix3x3(0, 0, -1, -1, 0, 0, 0, -1, 0));  // [19] gix=(1,1,0,1)
         ops.push_back(Matrix3x3(0, 1, 0, 0, 0, 1, -1, 0, 0));    // [20] gix=(1,1,0,2)
