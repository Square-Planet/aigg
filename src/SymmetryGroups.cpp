FOrbitType_SpecialPoints::FOrbitType_SpecialPoints(size_t iType_, char const *pDesc_, FPoint const &vExamplePoint_, FRotationMatrixList const &SymmetryOps)
   : FOrbitType(iType_, pDesc_, size_t(-1), 1)
{
   FPoint
      // we may get input points which do not lie on the sphere yet. Fix that.
      vExamplePoint = vExamplePoint_.normalized();
#ifdef INCLUDE_ABANDONED
//    std::cout << fmt::format("--- entered: FOrbitType_SpecialPoints(p = [{:10.4f},{:10.4f},{:10.4f}], SymmetryOps.size()={})\n",
//             double(vExamplePoint[0]), double(vExamplePoint[1]), double(vExamplePoint[1]), SymmetryOps.size());
#endif // INCLUDE_ABANDONED
   // collect all unique points of the orbit.
   FPointCloud
      PointCloud;
   for (size_t iSymOp = 0; iSymOp < SymmetryOps.size(); ++ iSymOp) {
      FPoint
         p = SymmetryOps[iSymOp] * vExamplePoint;
      ptrdiff_t
         iNextOrbitPt = ptrdiff_t(m_OrbitPoints.size());
      FPointCloud::FPointEntry
         e = PointCloud.Insert(p, iNextOrbitPt);
#ifdef INCLUDE_ABANDONED
//       std::cout << fmt::format("--- special pt orbit: p = [{:10.4f},{:10.4f},{:10.4f}] --> Rg p = [{:10.4f},{:10.4f},{:10.4f}] --> iPt = {}  new? -> {}  m_OrbitPoints.size() == {}\n",
//             double(vExamplePoint[0]), double(vExamplePoint[1]), double(vExamplePoint[1]),
//             double(p[0]), double(p[1]), double(p[2]), e.iPoint, int(e.iPoint == iNextOrbitPt), m_OrbitPoints.size());
#endif // INCLUDE_ABANDONED
      if (e.iPoint == iNextOrbitPt) {
         // this is a new point, which has not occurred in m_OrbitPoints yet.
         // Add it to the list.
         m_OrbitPoints.push_back(p);
      }
   }
   // fix up orbit length, now that we know it.
   this->Length = m_OrbitPoints.size();
#ifdef INCLUDE_ABANDONED
//    throw std::runtime_error("absicht!");
//    std::cout << fmt::format("--- FOrbitType_SpecialPoints({}, {}, [{:10.4f},{:10.4f},{:10.4f}]) --> length {}\n", iType_, pDesc_, double(vExamplePoint[0]), double(vExamplePoint[1]), double(vExamplePoint[1]),this->Length);
#endif // INCLUDE_ABANDONED
}

FOrbitType_SpecialPoints::~FOrbitType_SpecialPoints()
{
}


bool FOrbitType_SpecialPoints::IsOnOrbit(FPoint const &vPt, FScalar const &fEpsilon) const
{
   return (FindClosestPoint(vPt) - vPt).norm() < fEpsilon;
}


void FOrbitType_SpecialPoints::ProjectToOrbit(FPoint &vPt, bool AllowDiscreteChange) const
{
   assert(!m_OrbitPoints.empty());
   if (AllowDiscreteChange)
      // always return the canonical representative of the orbit.
      vPt = m_OrbitPoints.front();
   else
      // return the orbit representative which lies closest to the input point vPt
      vPt = FindClosestPoint(vPt);
}


void FOrbitType_SpecialPoints::ProjectTangentVectors(FVector3 **ppvTangents, size_t nTangents, FPoint const &vPt, FScalar *pErrSq) const
{
   for (size_t i = 0; i < nTangents; ++i) {
      // special point orbits have no continuous geometric degrees of freedom
      // -> *any* tangent vector will lead out of the orbit type.
      FVector3
         &v = *ppvTangents[i];
      v.setZero();
   }
}


FPoint const &FOrbitType_SpecialPoints::FindClosestPoint(FPoint const &vPt) const
{
   size_t
      iClosestPt = size_t(-1);
   FScalar
      fErr_ClosestPt = FScalar(1e77);
   for (size_t i = 0; i < m_OrbitPoints.size(); ++ i) {
      FScalar
         fErr = (m_OrbitPoints[i] - vPt).norm();
      if (i == 0 || fErr < fErr_ClosestPt) {
         iClosestPt = i;
         fErr_ClosestPt = fErr;
      }
   }
   return m_OrbitPoints[iClosestPt];
}



FOrbitType_SpecialPlanes::FOrbitType_SpecialPlanes(size_t iType_, char const *pDesc_,  FVector3 const &vPlaneNormal_, FRotationMatrixList const &SymmetryOps)
   : FOrbitType(iType_, pDesc_, size_t(-1), 1)
{
   FVector3
      // we may get input directions which do not lie on the sphere. Fix that.
      vPlaneNormal = vPlaneNormal_.normalized();

   // collect all unique plane normals obtained by transforming
   // the input plane through the group operations.
   FPointCloud
      PointCloud;
   for (size_t iSymOp = 0; iSymOp < SymmetryOps.size(); ++ iSymOp) {
      FVector3
         // NOTE:
         // - Technically we *should* transform the normals through
         //
         //   \[ n⃗' = \operatorname{solve}(R_g^T, n⃗), \]
         //
         //   rather than just multiplying by the $R_g$ matrices themselves.
         // - However, for $R_g\in O(3)$ we have
         //   \[ R_g^T = R_g^{−1}, \]
         //   so matrix $(R_g^T)^{−1}$ is equal to $R_g$ itself.
         // - For this reason transforming just by $R_g$ is sufficient—as
         //   long as we are guaranteed that the matrix representations of the
         //   symmetry operations are orthogonal.
         n = SymmetryOps[iSymOp] * vPlaneNormal;
      ptrdiff_t
         iNextOrbitPl = ptrdiff_t(m_PlaneNormals.size());
      FMappedPointCloud::FPointEntry
         e = PointCloud.Insert(n, iNextOrbitPl);
      if (e.iPoint == iNextOrbitPl) {
         // this is a new plane normal, which has not occurred in
         // m_PlaneNormals yet.
         // Add it to the list.
         m_PlaneNormals.push_back(n);
      }
   }
   // Fix up orbit length: the fact that points on the orbit have to fulfill the
   // plane equation should reduce the general orbit length by a factor of two.
   // (because the symmetry operation would make two points for all inputs which
   // do not lie exactly on the plane, but only one for points which do).
   // ⟹ orbit length should be length of a general orbit divided by two.
   //
   // There also cannot be any other condition on the orbit (e.g., it fulfilling
   // another plane equation), because otherwise there would be no remaining
   // continuous geometric degree of freedom, and therefore we would have a more
   // specialized special-points orbit instead of a special-planes orbit.
   // (note: this would not necessarily apply for space dimensions larger than 3!)
   this->Length = SymmetryOps.size() / 2;
#ifdef INCLUDE_ABANDONED
//    std::cout << fmt::format("--- FOrbitType_SpecialPlanes({}, {}, [{:10.4f},{:10.4f},{:10.4f}]) --> length {}\n", iType_, pDesc_, double(vPlaneNormal[0]), double(vPlaneNormal[1]), double(vPlaneNormal[1]),this->Length);
#endif // INCLUDE_ABANDONED
}

FOrbitType_SpecialPlanes::~FOrbitType_SpecialPlanes()
{
}


bool FOrbitType_SpecialPlanes::IsOnOrbit(FPoint const &vPt, FScalar const &fEpsilon) const
{
   return abs(FindClosestPlane(vPt).dot(vPt)) < fEpsilon;
}


void FOrbitType_SpecialPlanes::ProjectToOrbit(FPoint &vPt, bool AllowDiscreteChange) const
{
   FVector3
      n = FindClosestPlane(vPt);
   vPt -= n.dot(vPt) * n;
   FOrbitType::ProjectToOrbit(vPt, AllowDiscreteChange);
}


void FOrbitType_SpecialPlanes::ProjectTangentVectors(FVector3 **ppvTangents, size_t nTangents, FPoint const &vPt, FScalar *pErrSq) const
{
   FVector3
      n = FindClosestPlane(vPt);
#ifdef INCLUDE_ABANDONED
//    FVector3
//       n1 = FindClosestPlane(vPt),
//       n = n1.cross(vPt).normalized();
#endif // INCLUDE_ABANDONED
   for (size_t i = 0; i < nTangents; ++i) {
      // this is a plane orbit; the tangents have to lie within the plane.
      // ⟹ subtract components of `v` which are colinear with the plane normal.
      FVector3
         &v = *ppvTangents[i];
      FScalar
         fErr = v.dot(n);
      if (pErrSq)
         *pErrSq += sqr(fErr);
      v -= fErr * n;
   }
   // call base class; that one will take care of keeping the point on the sphere.
   FOrbitType::ProjectTangentVectors(ppvTangents, nTangents, vPt, pErrSq);
}


void FOrbitType_SpecialPlanes::ProjectRotation(FVector3 &vAxisAndAngle, FPoint const &vPt, FScalar *pErrSq) const
{
   FVector3
      n = FindClosestPlane(vPt);
   // this is a plane orbit. Any valid rotation preserving the orbit type
   // has to happen within the plane ⟹ rotation axis must be colinear with plane normal.
   FScalar
      f = vAxisAndAngle.dot(n);
   FVector3
      v = f * n;
   if (pErrSq)
      *pErrSq += (vAxisAndAngle - v).squaredNorm();
   vAxisAndAngle = v;
   // call base class; that one will take care of keeping the point on the sphere.
   FOrbitType::ProjectRotation(vAxisAndAngle, vPt, pErrSq);
}



FVector3 const &FOrbitType_SpecialPlanes::FindClosestPlane(FPoint const &vPt) const
{
   size_t
      iClosestPl = size_t(-1);
   FScalar
      fErr_ClosestPl = FScalar(1e77);
   for (size_t i = 0; i < m_PlaneNormals.size(); ++ i) {
      FScalar
         fErr = abs(m_PlaneNormals[i].dot(vPt));
      if (i == 0 || fErr < fErr_ClosestPl) {
         iClosestPl = i;
         fErr_ClosestPl = fErr;
      }
   }
   return m_PlaneNormals[iClosestPl];
}



FScalar CalcSpherialTriangleArea(FVector3 const &v0, FVector3 const &v1, FVector3 const &v2)
{
   // Lei, Qi, Tian, Eq. (6)/(7) Appl. Sci. 2020, 10, 655; doi:10.3390/app10020655
   // returns spherical area (=covered solid angle) of spherical triangle
   // (=set of three great circle arcs) represented by points-on-the-sphere
   // {v⃗₀, v⃗₁, v⃗₂}.
   // v⃗₀, v⃗₁, v⃗₂ are silently are assumed to lie on the unit sphere (i.e., have unit
   // norm), and not represent an degenerate/impossible spherical triangle.
   assert(IsAlmostZero(v0.norm() - FScalar(1)) && IsAlmostZero(v1.norm() - FScalar(1)) && IsAlmostZero(v2.norm() - FScalar(1)));

   // cgk note: I replaced the tangent fraction by atan2, which should take care
   // of some singularities. But I did not think about this very hard as far as
   // boudary cases of degenerate and slightly-negative-area triangles (due to
   // rounding artifacts) are concerned.
   return 2*atan2(v0.dot(v1.cross(v2)), (FScalar(1) + v0.dot(v1) + v1.dot(v2) + v2.dot(v0)));
}


FPoint FTriangle::MakeBarycentric(FPoint const &vCartPt, FBarycentricCoordType GeomType) const
{
   if (GeomType == GEOMTYPE_Planar) {
      // if this becomes noticeable in terms of cost we should just
      // store the matrix decomposition.
      FMatrix33
         V;
      V.col(0) = v0;
      V.col(1) = v1;
      V.col(2) = v2;
      return Solve(V, vCartPt);
   } else {
      cx_assert_rt(GeomType == GEOMTYPE_Spherical);

      // we take the "barycentric" name literally in this case: we just compute
      // the areas of the spherical triangle v0/v1/v2, and all three sub-
      // triangles with one vertex replaced by vPt, and divide them by each
      // other. Unlike in the planar case, this one may explode in case of
      // points outside of or on the boundary of the spherical triangle — needs testing.
      FVector3
         v0Sph = this->v0.normalized(),
         v1Sph = this->v1.normalized(),
         v2Sph = this->v2.normalized(),
         vPtSph = vCartPt.normalized();
      FScalar
         InvS = FScalar(1)/CalcSpherialTriangleArea(v0Sph, v1Sph, v2Sph);
      FPoint
         Out;
      Out[0] = InvS * CalcSpherialTriangleArea(vPtSph, v1Sph, v2Sph);
      Out[1] = InvS * CalcSpherialTriangleArea(v0Sph, vPtSph, v2Sph);
      Out[2] = InvS * CalcSpherialTriangleArea(v0Sph, v1Sph, vPtSph);
      return Out;
   }
}


FPoint FTriangle::MakeCartesian(FPoint const &vBarycPt, FBarycentricCoordType GeomType) const
{
   if (GeomType == GEOMTYPE_Planar) {
      return vBarycPt[0] * v0 + vBarycPt[1] * v1 + vBarycPt[2] * v2;
   } else {
      cx_assert_rt(GeomType == GEOMTYPE_Spherical);
      // map triangle vertices to sphere (in case they aren't on input)
      FMatrix33
         VSph;
      VSph.col(0) = this->v0.normalized();
      VSph.col(1) = this->v1.normalized();
      VSph.col(2) = this->v2.normalized();

      // Lei, Qi, Tian, Eq. (9)/(10) Appl. Sci. 2020, 10, 655; doi:10.3390/app10020655
      FScalar
         // 1/2 S
         f05_S = FScalar(.5)*CalcSpherialTriangleArea(VSph.col(0), VSph.col(1), VSph.col(2));
      FVector3
         k;
      FMatrix33
         A;
      for (int ix = 0; ix <= 2; ++ ix) {
         int
            iy = (ix+1) % 3,
            iz = (iy+1) % 3;
         if (IsAlmostZero(vBarycPt[ix] - FScalar(1)) && IsAlmostZero(vBarycPt[iy]) && IsAlmostZero(vBarycPt[iz])) {
//             std::cout << fmt::format(" TRIGGERED VERTEX RETURN, ix = {}\n", ix);
            // we will get a singular linear system in the case that one
            // coordinate lies directly on the vertex.
            return VSph.col(ix);
         }
         FScalar
            f = tan(f05_S*vBarycPt[ix]);
         k[ix] = f*(1 + VSph.col(iy).dot(VSph.col(iz)));
         A.col(ix) = FVector3(VSph.col(iy).cross(VSph.col(iz)) - f * (VSph.col(iy) + VSph.col(iz)));
      }

      return Solve(A.transpose(), k);
   }
}

// returns whether the point `vPt`, given in terms of Cartesian coordinates,
// lies inside the triangle (up to a numerical accuracy of `Epsilon`).
//
// It is assumed that the point given by `vCartesianCoords` lies on the
// triangle plane.
bool FTriangle::IsInside_Cartesian(FPoint const &vCartPt, FScalar const &Epsilon, FBarycentricCoordType GeomType) const
{
   if (1) {
      return IsInside_Barycentric(MakeBarycentric(vCartPt, GeomType), Epsilon);
      // ⬑ note: If I am not very mistaken, this test will return the same result
      // regardless of whether the area test is computed in terms of planar or
      // spherical geometry. And the planar one is cheaper, so that is what we do.
      // Should probably be tested at some point.
      // UPDATE: Hmpf… that only works if we project to the plane first. Don't want
      // to deal with it, just passing actual coord type for now.
   } else {
      // hm… no, this doesn't work. stupid spherical geometry :/. Have to
      // use the other one. And be very careful with it. Never feed it anything
      // which can't be converted.
      FVector3
         n = ((v1-v0).cross(v2-v0)).normalized();
      FScalar
         d = n.dot(v0);
      FVector3
         vCartPt_On_Plane = vCartPt - n*(n.dot(vCartPt) - d);
      return IsInside_Barycentric(MakeBarycentric(vCartPt_On_Plane, GEOMTYPE_Planar), Epsilon);
   }
}


// returns whether the point `vPt`, given in terms of Barycentric coordinates,
// lies inside the triangle (up to a numerical accuracy of `Epsilon`).
bool FTriangle::IsInside_Barycentric(FPoint const &vBarycPt, FScalar const &Epsilon) const
{
   assert(Epsilon >= FScalar(0));
   return vBarycPt[0] >= -Epsilon && vBarycPt[1] >= -Epsilon && vBarycPt[2] >= -Epsilon;
}



FPointGroupPtr MakePointGroup(std::string const &Name)
{
   FPointGroupPtr
      pPointGroup;
   if (Name == "icosahedral" || Name == "ico" || Name == "I")
      pPointGroup = new FIcosahedralGroup(FIcosahedralGroup::GROUP_RotationsOnly_I);
   else if (Name == "icosahedral-full" || Name == "icoh" || Name == "Ih")
      pPointGroup = new FIcosahedralGroup(FIcosahedralGroup::GROUP_Full_Ih);
   else if (Name == "tetrahedral" || Name == "tetra" || Name == "tet" || Name == "T")
      pPointGroup = new FTetrahedralGroup(FTetrahedralGroup::GROUP_RotationsOnly_T);
   else if (Name == "tetrahedral-full" || Name == "tetd" || Name == "Td")
      pPointGroup = new FTetrahedralGroup(FTetrahedralGroup::GROUP_FullAchiral_Td);
   else if (Name == "pyritohedral" || Name == "teth" || Name == "Th")
      pPointGroup = new FTetrahedralGroup(FTetrahedralGroup::GROUP_Chiral_Th);
   else if (Name == "octahedral" || Name == "octa" || Name == "oct" || Name == "O")
      pPointGroup = new FOctahedralGroup(FOctahedralGroup::GROUP_RotationsOnly_O);
   else if (Name == "octahedral-full" || Name == "octh" || Name == "Oh")
      pPointGroup = new FOctahedralGroup(FOctahedralGroup::GROUP_Full_Oh);
   else
      throw std::runtime_error(fmt::format("point group '{}' not recognized. Know 'icosahedral', 'icosahedral-full', 'tetrahedral', 'tetrahedral-full', 'octahedral', 'octahedral-full', 'pyritohedral'.", Name));
   return pPointGroup;
}
