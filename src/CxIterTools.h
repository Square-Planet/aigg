   /// As enumerate(seq), but allows customizing the returned type for
   /// the indices and values. This is specified in terms of a class template of the form
   /// `template<typename I, typename V> struct iav_t<I,V>{...}`.
   /// This construction can be used to define non-trivial transformations on
   /// the input sequence, to define custom ordering operators (operator <), or
   /// similar. Examples:
   /// ```
   ///     #include <iostream>
   ///     #include <vector>
   ///     #include <cmath>
   ///     #include "CxIterTools.h"
   ///
   ///     // make a basic index_and_value struct with just two data members;
   ///     // additionally, add a non-standard `operator <` to get sorted(...)
   ///     // to sort by key (index,value) in reverse.
   ///     template<typename index_t, typename value_t>
   ///     struct my_iav_t {
   ///        index_t my_index; value_t my_value;
   ///
   ///        bool operator < (my_iav_t const &other) const {
   ///           return std::tie(other.my_index, other.my_value) < std::tie(this->my_index, this->my_value);
   ///        }
   ///     };
   ///
   ///     // enumerate<iav_t> will be instanciate the class as iav_t<I,V>{i,v}.
   ///     // However, what you do with it is up to you. This class template
   ///     // computes powers v^i instead of storing indices i and values v.
   ///     template<typename index_t, typename value_t>
   ///     struct my_pow_trafo_t {
   ///        double m_value;
   ///        my_pow_trafo_t(index_t i, value_t v) : m_value{std::pow((double)v,i)} {}
   ///        operator double() const { return m_value; }
   ///     };
   ///
   ///     namespace it = cx::iter;
   ///     int main() {
   ///        std::vector<int> seq{3,5,2,4,12,1};
   ///        std::cout << "it::sorted(it::enumerate(seq)):\n";
   ///        for (auto e : it::sorted(it::enumerate(seq))) {
   ///           std::cout << "  seq[" << e.i << "] = " << e.v << std::endl;
   ///        }
   ///        std::cout << "it::enumerate<my_iav_t>(seq):\n";
   ///        for (auto e : it::enumerate<my_iav_t>(seq)) {
   ///           std::cout << "  seq[" << e.my_index << "] = " << e.my_value << std::endl;
   ///        }
   ///        std::cout << "it::sorted(it::enumerate<my_iav_t>(seq)):\n";
   ///        for (auto e : it::sorted(it::enumerate<my_iav_t>(seq))) {
   ///           std::cout << "  seq[" << e.my_index << "] = " << e.my_value << std::endl;
   ///        }
   ///        std::cout << "it::enumerate<my_pow_trafo_t>(seq):\n";
   ///        for (auto e : it::enumerate<my_pow_trafo_t>(seq)) {
   ///           std::cout << "  " << e << std::endl;
   ///        }
   ///     }
   /// ```
   /// Possible output:
   /// ```
   ///     it::sorted(it::enumerate(seq)):
   ///       seq[5] = 1
   ///       seq[2] = 2
   ///       seq[0] = 3
   ///       seq[3] = 4
   ///       seq[1] = 5
   ///       seq[4] = 12
   ///     it::enumerate<my_iav_t>(seq):
   ///       seq[0] = 3
   ///       seq[1] = 5
   ///       seq[2] = 2
   ///       seq[3] = 4
   ///       seq[4] = 12
   ///       seq[5] = 1
   ///     it::sorted(it::enumerate<my_iav_t>(seq)):
   ///       seq[5] = 1
   ///       seq[4] = 12
   ///       seq[3] = 4
   ///       seq[2] = 2
   ///       seq[1] = 5
   ///       seq[0] = 3
   ///     it::enumerate<my_pow_trafo_t>(seq):
   ///       1
   ///       5
   ///       4
   ///       64
   ///       20736
   ///       1
   /// ```
   template<template<typename I, typename V> class iav_t, class FSequence>
   auto constexpr enumerate(FSequence &&sequence) noexcept
   -> iter_detail::TIndexedSequenceWrapper<FSequence, 0, iav_t> {
      return {std::forward<FSequence>(sequence)};
   }

