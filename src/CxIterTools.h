/// @file CxIterTools.h Iteration-sequence generation/transformation (note: used
/// to also contain C++ template/parameter pack meta-programming primitives,
/// which are now in `CxMetaLight.h` and `CxMeta.h`)
///
/// # Number/vector/point sequence generators
///
/// - Number sequence generators (typically for integers):
///   The following functions return lightweight meta-sequence objects
///   which generate the associated number sequence $S$ if iterated over:
///
///    | Sequence Generator             | Generated Sequence                   | Notes
///    |:-------------------------------|--------------------------------------|-----------------------
///    |   `auto numbers()      `       | $S := [0, 1, 2, ...]$                | infinite sequence
///    |   `auto numbers_from(b)`       | $S := [b, b + 1, b + 2, ...]$        | infinite sequence
///    |   `auto xrange(e)      `       | $S := [0, 1, 2, ..., e)$             | semi-open, e ∉ S
///    |   `auto irange(e)      `       | $S := [0, 1, 2, ..., e]$             | closed, includes e ∈ S
///    |   `auto xrange(b,e)    `       | $S := [b, b + 1, b + 2, ..., e)$     | semi-open, e ∉ S
///    |   `auto irange(b,e)    `       | $S := [b, b + 1, b + 2, ..., e]$     | closed, includes e ∈ S
///    |   `auto xrange(b,e,s)  `       | $S := [b, b + s, b + 2*s, ..., e)$   | semi-open, e ∉ S
///    |   `auto irange(b,e,s)  `       | $S := [b, b + s, b + 2*s, ..., e]$   | closed, includes e ∈ S
///
///   + The functions have one template argument `template <class scalar_t>`. `scalar_t` defines
///     the types of `e` (end/last), `b` (begin/first), and `s` (step), as well as the
///     output type of the meta-sequence iterators.
///
///   + Warnings:
///
///     - `numbers()` and `numbers_from(b)`: For finite integer types, the
///       sequences generated by will eventually wrap around. Use integer
///       types which are large enough to contain your target number range! Be
///       especially careful about ranges derived from literal types. E.g.,
///       ```
///           // iterates over `int`s only (often only 32bit!)
///           for (auto i : cx::iter::numbers_from(0)) { ... }
///
///           // iterates over `unsigned long long` numbers
///           for (auto i : cx::iter::numbers_from(0ull)) { ... }
///       ```
///     - `e` versus `s`: Atm, the meta-sequence iterators will check the end condition using a
///       test amounting to `*it == e`; that is, they check for *exact* equality. If the sequence
///       generated by your combination of `b` and `s` does not actually include `e`, or if you
///       use types and `b`/`e` values which induce inexact arithmetic (e.g., `float`/`double`
///       types and `b`,`e`, or `s` which cannot be exactly represented as binary floats), then
///       the meta-sequence will never meet its end condition.
///
///       E.g., `cx::iter::irange(0., 1., 0.1)` will not terminate on most platforms, because
///       `b`,`e`,`s` are all `double` literals, and `0.1` cannot be exactly represented in terms
///       of the IEEE binary64 floats which `double` typically maps to.
///
///   + Example:
///     ```
///         std::vector<char const *> vec{"aa", "bb", "cc", "dd"};
///         for (auto i : cx::iter::xrange(vec.size())) {
///            std::cout << "vec[" << i << "] = '" << vec[i] << "'\n";
///         }
///     ```
///     Output:
///     ``` output
///         [0] 'aa'
///         [1] 'aa'
///         [2] 'aa'
///         [3] 'aa'
///     ```
/// - Vector sequence generators / point sequence generators:
///
///   + `ray_grid(vfrom, vto, N, trafo = _Identity<>)`:
///     Return meta-sequence for a equidistant `N`-point grid along the ray
///
///     \f[ v(t) = (1 - t) v_\mathrm{from} + t v_\mathrm{to} \f]
///
///     which is subsequently mapped through the function `trafo`, if provided.
///     `N` must be >= 2, and `vfrom` and `vend` are both included.
///
/// # Meta-sequences for iteration
///
/// - `reversed(seq)`:
///    For a sequence with bidirectional iterators, return a meta-sequence which iterates
///    it in reverse.
///
/// - `cycle(seq)`:
///    Return a meta-sequence which cycles through an input sequence ad inifitum
///
/// - `repeat<FElement>(element, N)`:
///    Return a meta-sequence consisting of `N` repetitions of `element`
///
/// - `repeat<FElement>(element)`:
///    Return a meta-sequence `[e,e,e,...]` infinitely repeating e := `element`
///
/// - `mapv<FSequence, FTrafo>(seq, trafo)`:
///    `mapv(seq, trafo)` returns a meta-sequence corresponding to
///    `[trafo(e) for e in seq]`; that is, which maps the original sequence
///    elements through the function `trafo` on iterator dereferencing.
///
/// - `mapiv<FSequence, FTrafo>(seq, trafo)`:
///    `mapiv(seq, trafo)` returns a meta-sequence corresponding to
///    `[trafo(i,e) for (i,e) in enumerate(seq)]`; that is, which maps elements `seq[i]`
///    through `trafo(i, seq[i])` on iterator dereferencing.
///
/// - `deref(seq)`:
///    `deref(seq)` returns a meta-sequence which is equivalent to seq, except
///    that dereferencing its iterators returns operator* applied to the
///    original seq elements (`[*e for e in seq]`), rather than just the original
///    elements (`[e for e in seq]`) themselves.
///
///    This can be useful for handling sequences of pointers, smart-pointers, or
///    otherwise wrapped objects.
///
///    - see also: `template<class FBaseIt, unsigned N> using deref_iterator_t = ...;`
///
/// - `sorted(seq)`
///
/// - `sorted<FSequence, FSortKey>(seq, key)`
///
/// - `zip(seqs...)`:
///   `zip(A,B,C,...)` returns a meta-sequence over tuples with matching items
///   from `A`, `B`, `C`, ...:
///
///       zip(A,B,...) ≍ [tuple(A[i], B[i], ...) for i in range(min(len(A), len(B), ...)].
///
///   + WARNING: if reversed() is meant to be used with `zip()`, then all input sequences
///     must have the same length to yield correct results!
///   + Otherwise `zip(A,B,C,...)` will terminate on the shortest input sequence.
///
/// - `enumerate(seq)`
///
/// - `reversible_enumerate(seq)`:
///    As enumerate(seq), but returns a meta-sequence which can be subjected to `reversed()`.
///
