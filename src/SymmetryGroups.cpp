// Note on screening monomial functions:
//
// - At the very least, the I_h, O_h, and T_h groups (i.e., all extended
//   polyhedral groups except T_d) all include a $σ_{xyz}$ inversion operation.
//
//   Combined with the $σ_{xy}$, $σ_{yz}$, and $σ_{zx}$ which
//   are already included at the levels of the rotations-only groups $I$, $O$, and $T$,
//   this means that the groups then also contain *all* axis mirror operations
//   $σ_{x}$, $σ_{y}$, and $σ_{z}$ individually.
//
//   As a consequence, any monomial x^i y^j z^k in which any of i,j,k is odd
//   will now be automatically group-averaged to zero (this was not necessarily
//   the case for the base groups $I$ and $T$ at least!)
//
// - $T_d$ does not have this inversion operation as a group element.
//   However, unlike $T$ and $T_h$, which both include cyclic Cartesian coordinate
//   permuations (i.e., permutations in $S_3$ of even sign),
//
//   (x,y,z) ⟶ \{ (x,y,z), (y,z,x), (z,x,y) \},
//
//   the enlarged group $T_d$ now \emph{does} have all six Cartesian
//   coordinate permutations,
//
//   (x,y,z) ⟶ \{ (x,y,z), (y,z,x), (z,x,y), (y,x,z), (x,z,y), (z,y,x) \}
//
//   including such of odd sign. Consequently, we can extend the check for
//   unique cyclic $(i,j,k)$ by unique sets of general $(i,j,k)$.
//
// - Note:
//   - $I_h$ and $T_h$ still do not include all the coordinate permutations,
//     but only cyclic ones.
//   - $O$ also includes only cyclic permutations.
//     However, $O_h$ now includes all six coordinate permutations.
//
// - So, in summary:
//   - $T_h$, $O_h$, and $I_h$ include all of $σ_{x}$, $σ_{y}$,
//     and $σ_{z}$ as group elements, and therefore do not require
//     monomials x^i y^j z^k in the target space for which any of
//     $i$, $j$, or $k$ is odd
//   - $T_d$ and $O_h$ include all six Cartesian coordinate permutations
//     of $(x,y,z)$ as group elements (not only cyclic ones), and therefore
//     require no monomials x^i y^j z^k in the target space which do not
//     fulfill the condition i ≥ j ≥ k.


