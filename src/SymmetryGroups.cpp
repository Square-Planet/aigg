bool FTetrahedralGroup::CouldMonomialBeATargetFunction(unsigned ix, unsigned iy, unsigned iz) const
{
   // Note the following group elements:
   // [x,y,z]-coordinate permutation mirror symmetries in I and Ih:
   //
   // T:
   // included Cartesian coordinate permutations:
   //   [\id, π_{yzx}, π_{zxy}]
   // included axis aligned reflections:
   //   [\id, σ_{xy}, σ_{xz}, σ_{yz}]

   // Td:
   // included Cartesian coordinate permutations:
   //   [\id, π_{xzy}, π_{yxz}, π_{yzx}, π_{zxy}, π_{zyx}]
   // included axis aligned reflections:
   //   [\id, σ_{xy}, σ_{xz}, σ_{yz}]
   //
   // Th:
   // included Cartesian coordinate permutations:
   //   [\id, π_{yzx}, π_{zxy}]
   // included axis aligned reflections:
   //   [\id, σ_{xyz}, σ_{xy}, σ_{xz}, σ_{x}, σ_{yz}, σ_{y}, σ_{z}]

   // all groups include σ_{xy}, σ_{xz}, σ_{yz} as group elements.
   // As a result, they will automatically yield zero for all monomials m_ijk
   // with either one or two of ijk being odd numbers (see appendix in paper).
   bool
      ex = (ix % 2 == 0),
      ey = (iy % 2 == 0),
      ez = (iz % 2 == 0);
   bool
      AllEvenOrAllOdd = (ex == ey && ey == ez);
   if (!AllEvenOrAllOdd)
      return false;
   if (m_SubType == GROUP_Chiral_Th) {
      // this one also has σ_{x}, σ_{y}, and σ_{z} separately.
      // it will therefore automatically (correctly) yield zero for all m_ijk
      // for which any of i,j,k is odd.
      if (!ex || !ey  || !ez)
         return false;
   }
   if (!s_ChooseOneCanonicalRepresentativeInScreening)
      return true;

   if (m_SubType != GROUP_FullAchiral_Td) {
      // make monomials we know to yield the same group average.
      unsigned
         // T, Th, and Td all include cyclic permutations of x,y,z, we
         // definitely will need at most one of the cyclic images x^i y^j z^k,
         // x^j y^k z^i,  x^k y^i z^j
         M0[3] = {ix,iy,iz},
         M1[3] = {iz,ix,iy},
         M2[3] = {iy,iz,ix};
      // choose one of them as canonical representative of the equivalency class.
      if (!(M3LessEq(M0, M1) && M3LessEq(M0, M2)))
         return false;
   } else {
      // this one (Td) has also the acyclic [x,y,z] coordinate permutations.
      // So we can choose just one unique combination of {i,j,k} regardless
      // of order.
//       if (!((ix >= iy) && (iy >= iz)))
//          return false;
      if (!(ix <= iy && iy <= iz))
         return false;
   }

   return true;
}


