   /// Returns a meta-sequence wrapper which adds to each element of the original
   /// sequence a running index, starting at 0, just as python's `enumerate(seq)`.
   /// Concretely: enumerate(seq): for each e in seq, the meta sequence
   /// yields (ie,e), where
   ///
   /// - ie = 0 for e = *seq.begin()
   /// - ie = 1 for e = *(++iterator(begin))
   /// - ie = 2 for e = *(++(++iterator(begin())))
   ///
   /// Comments:
   /// - The input sequence does not need to have natural indices or a []
   ///   operator---the indices are kept track of as the iterators as progressed
   ///   (e.g., it will work fine for a std::list or std::set)
   ///
   /// - This version is NOT reversible (won't work with reversed()).
   ///   Use reversible_enumerate(seq) instead to get a enumeration meta-sequence
   ///   which can be used with reversed(seq).
   ///
   ///   Background:
   ///   - making a reversible meta-sequences would require enumerate() to call
   ///     `.size()` on the input sequence (to construct the `end()` iterator).
   ///   - Depending on the type of input sequence, this
   ///     could incur a non-negligible overhead (e.g., for std::lists, std::sets,
   ///     results of combinatorial meta-sequences (e.g., combinations(seq,K),
   ///     permutations(seq), groupby(seq,key), ...).
   ///   - For this reason, we disable this by default and instead provide an
   ///     alternative implementation (reversible_enumerate) which performs the
   ///     additional work.
   ///
   /// Efficiency:
   /// - No space overhead
   /// - Effectively no runtime overhead (compared to iterating over the
   ///   original sequence and keeping track of the indices yourself).
   /// Notes input sequence:
   /// - Will work on anything which has std::begin() and std::begin()
   ///   defined, and these functions returning something which is at least a
   ///   ForwardIterator
   ///   (https://en.cppreference.com/w/cpp/named_req/ForwardIterator).
   /// - This includes all std containers and user types which have .begin() and
   ///   .end() members, as well as raw C arrays, and any generator objects which
   ///   are *not* containers (e.g., std::vector<bool>, meta-sequences in this
   ///   file, or explicit sequences generators like ray_grid).
   /// - If the original sequence's iterators fulfill BidrectionalIterator, the
   ///   returned iterators of the meta-sequence will also be bidirectional.
   template<class FSequence>
   auto constexpr enumerate(FSequence &&sequence) noexcept
   -> iter_detail::TIndexedSequenceWrapper<FSequence, 0, basic_vai_t> {
//    -> iter_detail::TIndexedSequenceWrapper<FSequence, 0, iav<0>::template type> {
      return {std::forward<FSequence>(sequence)};
   }

