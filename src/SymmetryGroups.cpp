std::string FOctahedralGroup::Name(FPointGroupNameType NameType) const
{
   if (m_SubType == GROUP_RotationsOnly_O) {
      switch(NameType) {
         case NAMETYPE_Group: return "octahedral group";
         case NAMETYPE_Symmetry: return "octahedral";
         case NAMETYPE_Grid: return "octahedral grid";
         case NAMETYPE_Symbol: return "O";
      }
   } else if (m_SubType == GROUP_Full_Oh) {
      switch(NameType) {
         case NAMETYPE_Group: return "octahedral-full group";
         case NAMETYPE_Symmetry: return "octahedral-full";
         case NAMETYPE_Grid: return "octahedral-full grid";
         case NAMETYPE_Symbol: return "Oh";
      }
   }
   return "(?name-type)";
}


