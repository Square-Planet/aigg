         ops.push_back(Matrix3x3(1, 0, 0, 0, 1, 0, 0, 0, 1));    // [ 0] gix=(0,0,0,0)
         ops.push_back(Matrix3x3(0, 0, -1, -1, 0, 0, 0, 1, 0));  // [ 1] gix=(0,0,0,1)
         ops.push_back(Matrix3x3(0, -1, 0, 0, 0, 1, -1, 0, 0));  // [ 2] gix=(0,0,0,2)
         ops.push_back(Matrix3x3(1, 0, 0, 0, -1, 0, 0, 0, -1));  // [ 3] gix=(0,0,1,0)
