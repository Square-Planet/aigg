         ops.push_back(Matrix3x3(0, 1, 0, 0, 0, -1, -1, 0, 0));   // [ 5] gix=(0,0,1,2)
         ops.push_back(Matrix3x3(-1, 0, 0, 0, 1, 0, 0, 0, -1));   // [ 6] gix=(0,1,0,0)
