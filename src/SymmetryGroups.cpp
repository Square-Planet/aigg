void FOrbitType::ProjectTangentVectors(FVector3 **ppvTangents, size_t nTangents, FPoint const &p, FScalar *pErrSq) const
{
   for (size_t i = 0; i < nTangents; ++i) {
      // project out rotational component along axis of vPt. Not supposed to be there.
      FVector3
         &v = *ppvTangents[i];
      FScalar
         fOrthErr = v.dot(p);
      v -= p * fOrthErr;
      if (pErrSq)
         *pErrSq += sqr(fOrthErr);
   }
}

void FOrbitType::ProjectRotation(FVector3 &vAxisAndAngle, FPoint const &vPt, FScalar *pErrSq) const
{
   // rotation axis cannot be colinear with point itself.
   FScalar
      fOrthErr = vAxisAndAngle.dot(vPt);
   vAxisAndAngle -= vPt * fOrthErr;
   if (pErrSq)
      *pErrSq += sqr(fOrthErr);
}



